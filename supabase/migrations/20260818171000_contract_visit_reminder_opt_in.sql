-- 정기계약 현장에 '내일 방문 예정이에요'를 보낼지 계약마다 정한다. 기본은 안 보냄.
--
-- 왜 필요한가:
-- 리마인더 크론에 정기계약 필터가 없어서, 주 5회 오는 거래처에 매 평일마다
-- "내일 방문 예정이에요"가 나가고 있었다(닥터홍마취통증의학과의원 — 월~금 방문,
-- 앞으로 예정된 방문만 44건). 매일 오는 걸 아는 거래처에 매일 보내는 안내는
-- 정보가 아니라 소음이고, 발송 비용도 그만큼 나간다.
--
-- 기본값을 false(안 보냄)로 두는 이유: 정기 거래처는 방문 요일이 고정돼 있어
-- 전날 안내가 필요 없는 경우가 대부분이다. 월 1회처럼 간격이 긴 계약만
-- 사장님이 계약 수정 창에서 켜면 된다. 일회성 예약은 이 칸과 무관하게 항상 나간다.

alter table public.contracts
  add column if not exists send_visit_reminder boolean not null default false;

comment on column public.contracts.send_visit_reminder is
  '이 정기계약의 방문 전날 안내 알림톡을 보낼지. 기본 false(안 보냄) — 매일/매주 오는 현장에 매번 보내면 소음이 된다. 일회성 예약은 이 값과 무관하게 항상 보낸다.';
