// 표에 들어 있는 마지막 연도. 이 뒤의 날짜는 공휴일 판정을 할 수 없으므로
// (아직 안 채운 해를 '평일'로 단정하지 않도록) 호출부에서 알 수 있게 노출한다.
export const KR_HOLIDAY_LAST_YEAR = 2027

/** 그날의 공휴일 이름. 공휴일이 아니면 null. (date = 'YYYY-MM-DD', KST) */
export function getHolidayName(date: string): string | null {
  return KR_HOLIDAYS[date] ?? null
}

/** 그날이 공휴일인가. (date = 'YYYY-MM-DD', KST) */
export function isHoliday(date: string): boolean {
  return date in KR_HOLIDAYS
}

/** 기준표가 아직 못 미치는 미래 날짜인가 — 안내 문구에서 '확인 필요'를 띄울 때 쓴다. */
export function isBeyondHolidayTable(date: string): boolean {
  return Number(date.slice(0, 4)) > KR_HOLIDAY_LAST_YEAR
}
